const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'knovera-community-'));
process.env.COMMUNITY_DB_PATH = path.join(dir, 'test.sqlite');
const cache = new Map();
function load(file) {
  const filename = path.resolve(__dirname, '..', file);
  if (cache.has(filename)) return cache.get(filename).exports;
  const mod = new Module(filename, module);
  mod.paths = Module._nodeModulePaths(path.dirname(filename));
  const original = mod.require.bind(mod);
  mod.require = id => id.startsWith('.') ? load(path.relative(path.resolve(__dirname, '..'), path.resolve(path.dirname(filename), id + '.ts'))) : original(id);
  cache.set(filename, mod);
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  mod._compile(compiled, filename);
  return mod.exports;
}
const server = load('lib/community/server.ts');
after(() => { server.communityDb().close(); fs.rmSync(dir, { recursive: true, force: true }); });
test('member authentication, shared replies, privacy, conflicts, and moderation', () => {
  const alice = server.authenticate('register', 'test-alice', 'Example-pass-2468', 'Alice');
  const bob = server.authenticate('register', 'test-bob', 'Example-pass-3579', 'Bob');
  assert.equal(server.sessionMember(alice.token).id, alice.member.id);
  assert.equal(server.authenticate('login', 'test-alice', 'Example-pass-2468').member.id, alice.member.id);
  assert.throws(() => server.authenticate('login', 'test-alice', 'Wrong-password'), error => error.status === 401);
  assert.throws(() => server.authenticate('register', 'test-alice', 'Example-pass-2468', 'Imposter'), error => error.status === 409);
  assert.equal(server.sessionMember('forged-token'), null);
  let saved = server.changeActivity(alice.member.id, { revision: 0, field: 'joined', id: 'the-focus-room', value: true });
  saved = server.changeActivity(alice.member.id, { revision: saved.revision, field: 'notes', id: 'protecting-your-first-hour', value: 'Private reflection' });
  assert.equal(server.getActivity(alice.member.id).activity.notes['protecting-your-first-hour'], 'Private reflection');
  assert.deepEqual(server.getActivity(bob.member.id).activity.notes, {});
  assert.throws(() => server.changeActivity(alice.member.id, { revision: 0, field: 'saved', id: 'protecting-your-first-hour', value: true }), error => error.status === 409);
  assert.equal(server.getActivity(alice.member.id).revision, saved.revision);
  assert.throws(() => server.changeActivity(alice.member.id, { revision: saved.revision, field: 'notes', id: 'protecting-your-first-hour', value: 'Overwrite an outdated draft', previousValue: 'An older reflection' }), error => error.status === 409);
  assert.throws(() => server.changeActivity(alice.member.id, { revision: saved.revision, field: 'completed', id: 'the-focus-room:999', value: true }), error => error.status === 404);
  const thread = server.createThread(alice.member, { circle: 'the-focus-room', title: 'How do you protect your reading time?', body: 'A development conversation.' });
  assert.equal(server.threadById(thread.id).author, 'Alice');
  assert.equal(server.threads('the-focus-room').length, 1);
  assert.equal(server.threads('small-steps-club').length, 0);
  server.createReply(bob.member, { discussion: thread.id, body: 'I read before checking my phone.' });
  const reply = server.replies(thread.id)[0];
  server.createReply(alice.member, { discussion: thread.id, parentId: reply.id, body: 'That is a helpful idea.' });
  assert.equal(server.replies(thread.id)[1].parentId, reply.id);
  assert.throws(() => server.createReply(alice.member, { discussion: 'missing', body: 'Invalid reply' }), error => error.status === 404);
  assert.throws(() => server.createReply(alice.member, { discussion: 'protecting-your-first-hour', parentId: reply.id, body: 'Wrong conversation' }), error => error.status === 404);
  assert.throws(() => server.createReply(alice.member, { discussion: thread.id, body: ' ' }), error => error.status === 400);
  assert.throws(() => server.moderate(alice.member, { kind: 'reply', id: reply.id, action: 'hide' }), error => error.status === 403);
  server.moderate(alice.member, { kind: 'reply', id: reply.id, action: 'report', reason: 'Please review this reply.' });
  assert.equal(server.communityDb().prepare('SELECT COUNT(*) AS count FROM reports WHERE resolved=0').get().count, 1);
  process.env.COMMUNITY_MODERATOR_IDS = alice.member.id;
  const moderator = server.sessionMember(alice.token);
  assert.equal(moderator.moderator, true);
  server.moderate(moderator, { kind: 'reply', id: reply.id, action: 'dismiss' });
  assert.equal(server.communityDb().prepare('SELECT COUNT(*) AS count FROM reports WHERE resolved=0').get().count, 0);
  server.moderate(alice.member, { kind: 'reply', id: reply.id, action: 'report', reason: 'Review again after dismissal.' });
  assert.equal(server.communityDb().prepare('SELECT COUNT(*) AS count FROM reports WHERE resolved=0').get().count, 1);
  server.moderate(moderator, { kind: 'reply', id: reply.id, action: 'hide' });
  assert.equal(server.replies(thread.id)[0].body, '[Reply removed]');
  assert.equal(server.replies(thread.id).length, 2, 'Child replies survive parent moderation');
  assert.equal(server.communityDb().prepare('SELECT COUNT(*) AS count FROM reports WHERE resolved=0').get().count, 0);
  server.moderate(moderator, { kind: 'reply', id: reply.id, action: 'restore' });
  assert.equal(server.replies(thread.id)[0].body, 'I read before checking my phone.');
  server.logout(alice.token);
  assert.equal(server.sessionMember(alice.token), null);
  const hash = server.communityDb().prepare('SELECT password FROM members WHERE id=?').get(alice.member.id).password;
  assert.notEqual(hash, 'Example-pass-2468');
  const session = server.communityDb().prepare('SELECT token FROM sessions WHERE member=?').get(bob.member.id).token;
  assert.notEqual(session, bob.token);
});
